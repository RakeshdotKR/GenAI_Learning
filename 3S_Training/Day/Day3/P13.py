"""
P13.py — Pydantic for Structured Output Validation

SUMMARY:
This program defines a Pydantic model describing the contact information expected
from the LLM. PydanticOutputParser uses that model to guide output formatting and
parse the response into a ContactInfo object. The program prints the object and
accesses its fields as attributes.

PREREQUISITES:
- Ollama running with phi3:mini downloaded.
- Install: pip install pydantic langchain-core langchain-ollama
"""

# Import Pydantic's base class for data models and Field for field descriptions.
from pydantic import BaseModel, Field
# Import LangChain's chat prompt template class.
from langchain_core.prompts import ChatPromptTemplate
# Import the parser that validates and creates a Pydantic object from model output.
from langchain_core.output_parsers import PydanticOutputParser
# Import the local Ollama chat-model integration.
from langchain_ollama import ChatOllama
# Optional Gemini alternative; use it only after configuring credentials.
# from langchain_google_genai import ChatGoogleGenerativeAI

# Select the local model.
MODEL = "phi3:mini"
# Alternative model; uncomment if available in Ollama.
# MODEL = "gemma2:2b"

# Define the structure and expected fields for extracted contact information.
class ContactInfo(BaseModel):
    # Require a string for the person's full name and document its meaning.
    name: str = Field(description="Full name of the person")
    # Require a string for the email address.
    email: str = Field(description="Email address")
    # Require a string describing the intent category.
    intent: str = Field(description="One of: complaint, inquiry, feedback")

# Create the local model wrapper with low randomness.
llm = ChatOllama(model=MODEL, temperature=0.0)
# Configure a parser to parse model output into the ContactInfo Pydantic model.
parser = PydanticOutputParser(pydantic_object=ContactInfo)

# Define a prompt that includes format instructions and the source text.
template = ChatPromptTemplate.from_messages([
    ("human", """Extract contact info from the text.
{format_instructions}

Text: {text}"""),
])

# Connect the prompt, model, and parser into a single runnable chain.
chain = template | llm | parser

# Execute the chain with source text and instructions generated by the parser.
result = chain.invoke({
    "text": "Hello, I'm Deepa (deepa@mail.com). I want to know my order status.",  # Input to extract.
    "format_instructions": parser.get_format_instructions(),  # Required output shape.
})

# Print the parsed ContactInfo object.
print(result)
# Access the name and intent using attributes defined by the Pydantic model.
print(f"Name: {result.name}, Intent: {result.intent}")
