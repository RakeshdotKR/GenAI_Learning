
"""
P1.py — System Prompt vs User Prompt

SUMMARY:
This program demonstrates the difference between a system prompt and a user
prompt by using a locally running language model through Ollama.

1. The system prompt defines the AI's role, behavior, tone, and boundaries.
2. The user prompt provides the customer's actual question.
3. The OpenAI Python SDK communicates with Ollama's local API.
4. The model generates a response based on the supplied messages.
5. The generated response is printed without leading or trailing whitespace.

PREREQUISITES:
- Ollama must be installed and running.
- The selected model must be available locally.
- The OpenAI Python SDK must be installed:
  pip install openai

EXAMPLE MODEL:
- phi3:mini
  Download it using: ollama pull phi3:mini
"""

# Import the OpenAI class from the OpenAI Python SDK.
# We use this SDK because Ollama provides an OpenAI-compatible API.
from openai import OpenAI

# Specify which language model Ollama should use.
# phi3:mini is a relatively small model suitable for local experimentation.
MODEL = "phi3:mini"

# This is an alternative model selection.
# Remove the comment symbol (#) to use this model instead.
# Make sure the model has been downloaded into Ollama first.
# MODEL = "gemma2:2b"

# Create an API client that communicates with the local Ollama server.
# base_url specifies the address of Ollama's OpenAI-compatible API.
# The /v1 endpoint exposes API routes compatible with the OpenAI SDK.
# api_key is supplied because the SDK expects a key; Ollama's local API
# generally does not require a real OpenAI API key.
client = OpenAI(
    base_url="http://localhost:11434/v1",
    api_key="ollama"
)

# Send a chat completion request to the selected language model.
# The response generated by the model will be stored in variable r.
r = client.chat.completions.create(

    # Tell Ollama which language model should generate the response.
    model=MODEL,

    # Supply the conversation as a list of messages.
    # Each message has a role and content.
    messages=[

        # SYSTEM PROMPT:
        # The system message establishes the assistant's role and rules.
        # It instructs the model to act as a customer support agent
        # for a mobile phone company named Nova Phones.
        {
            "role": "system",

            # The content contains the behavioral instructions.
            # The adjacent strings are automatically joined into one string
            # because they are enclosed in parentheses.
            "content": (
                # Define the assistant's role and company.
                "You are a customer support agent for a mobile phone company called Nova Phones. "

                # Specify the desired response style.
                "Be polite, concise, and only answer questions related to Nova Phones products. "

                # Define the response for questions outside the permitted scope.
                "If asked anything unrelated, say: 'I can only help with Nova Phones queries.'"
            )
        },

        # USER PROMPT:
        # The user message contains the customer's actual question.
        # Unlike the system prompt, it does not define the assistant's role.
        {
            "role": "user",

            # This is the customer's battery-related question.
            "content": "My battery drains in 3 hours. What should I do?"
        },
    ],

    # Limit the maximum number of generated tokens in the response.
    # A token can be a word, part of a word, or punctuation.
    # This is a generation limit, not a guaranteed word count.
    max_tokens=150,

    # Control the randomness of the generated response.
    # A lower value generally makes responses more predictable.
    # A higher value generally allows more variation.
    temperature=0.3,
)

# Extract the text content from the first generated choice.
# choices[0] selects the first response returned by the model.
# message.content contains the assistant's generated text.
# strip() removes whitespace from the beginning and end of the text.
# print() displays the final response in the terminal.
print(r.choices[0].message.content.strip())
